"""Zero-call audit of the memory layer on the existing LongMemEval-S stores.

Run: `python tools/layer_audit.py [split ...]` (default: train150 dev100 heldout100).
Writes `results/analysis/layer-audit-v1.json` and `.md`. Read-only on the stores; no
model calls. The numbers are development evidence on exposed splits.

What it measures, per split and question type:

- `replaces_without_predecessor`: memories Stage B marked `replaces` that have no earlier
  memory under the same `(user, subject, predicate)` — a replacement with nothing to
  replace, which the resolver can only ignore.
- `ku_same_key`: multi-session knowledge-update questions where memories from two
  different gold sessions share some key. A lead, not an update-accuracy figure: it is
  necessary for the resolver to see the old and new value together, but the shared key
  need not belong to the pair that should update (an upper bound on that).
- `ku_superseded`: of those questions, how many have *any* superseded memory among the
  gold evidence — not necessarily the old value the question is about.
- `pref_memory_on_gold_session`: preference questions with a preference-scoped memory
  extracted from a gold session.
- `memory_on_gold_turn`: questions with any memory anchored to a turn LongMemEval marks
  `has_answer`.
"""

from __future__ import annotations

import json
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from llm_long_term_memory.store.session_keys import external_session_id  # noqa: E402

OUT = REPO / "results/analysis/layer-audit-v1"


def _store_counts(con: sqlite3.Connection) -> dict:
    one = lambda sql: con.execute(sql).fetchone()[0]  # noqa: E731
    return {
        "memories": one("select count(*) from memories"),
        "assistant_memories": one("select count(*) from memories where source_role='assistant'"),
        "superseded": one("select count(*) from memories where status='superseded'"),
        "replaces": one("select count(*) from memories where update_op='replaces'"),
        "replaces_without_predecessor": one(
            "select count(*) from memories m where update_op='replaces' and not exists ("
            " select 1 from memories p where p.user_id=m.user_id and p.subject=m.subject"
            " and p.predicate=m.predicate and p.id<>m.id"
            " and coalesce(p.valid_from,p.ingested_at)<=coalesce(m.valid_from,m.ingested_at))"
        ),
        "predicates": one("select count(distinct predicate) from memories"),
        "predicates_used_once": one(
            "select count(*) from (select predicate from memories group by predicate"
            " having count(*)=1)"
        ),
    }


def audit_split(questions: dict, qids: list[str], con: sqlite3.Connection) -> dict:
    by_type: dict[str, Counter] = defaultdict(Counter)
    for qid in qids:
        q = questions[qid]
        qtype = q["question_type"] + ("_abs" if qid.endswith("_abs") else "")
        gold = set(q["answer_session_ids"])
        gold_turns = {
            (sid, i)
            for sid, session in zip(q["haystack_session_ids"], q["haystack_sessions"], strict=True)
            for i, turn in enumerate(session)
            if turn.get("has_answer")
        }
        rows = con.execute(
            "select subject, predicate, type, scope, status, source_session_id,"
            " source_turn_index from memories where user_id=?",
            (qid,),
        ).fetchall()
        on_session = [r for r in rows if external_session_id(r[5]) in gold]
        on_turn = [r for r in rows if (external_session_id(r[5]), r[6]) in gold_turns]
        c = by_type[qtype]
        c["questions"] += 1
        c["memory_on_gold_turn"] += bool(on_turn)
        c["memory_on_gold_session"] += bool(on_session)
        if qtype == "single-session-preference":
            c["pref_memory_on_gold_session"] += any(
                r[3] == "preference" or r[2] == "preference" for r in on_session
            )
        if qtype == "knowledge-update" and len(gold) >= 2:
            evidence = on_turn or on_session
            keys: dict[tuple, set] = defaultdict(set)
            for r in evidence:
                keys[(r[0], r[1])].add(external_session_id(r[5]))
            c["ku_multi_session"] += 1
            c["ku_same_key"] += any(len(v) >= 2 for v in keys.values())
            c["ku_superseded"] += any(r[4] == "superseded" for r in evidence)
    total = Counter()
    for c in by_type.values():
        total.update(c)
    return {"by_type": {k: dict(v) for k, v in sorted(by_type.items())}, "all": dict(total)}


def render(report: dict) -> str:
    lines = [
        "# Memory-layer audit (zero calls)",
        "",
        "> Generated by `tools/layer_audit.py`. Exposed development splits; read-only on",
        "> the stores. Not an accuracy result. The two KU columns are leads, not update",
        "> precision or recall; see the tool docstring.",
        "",
        "| split | memories | assistant | superseded | replaces w/o predecessor |"
        " predicates used once | KU: two gold sessions share a key (upper bound) |"
        " KU: some gold-evidence memory superseded |"
        " preference memory on gold | any memory on gold turn |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for split, r in report["splits"].items():
        s, a = r["store"], r["questions"]["all"]
        pref = r["questions"]["by_type"].get("single-session-preference", {})
        lines.append(
            f"| {split} | {s['memories']:,} | {s['assistant_memories']:,} | {s['superseded']} |"
            f" {s['replaces_without_predecessor']}/{s['replaces']} |"
            f" {s['predicates_used_once']:,}/{s['predicates']:,} |"
            f" {a.get('ku_same_key', 0)}/{a.get('ku_multi_session', 0)} |"
            f" {a.get('ku_superseded', 0)}/{a.get('ku_multi_session', 0)} |"
            f" {pref.get('pref_memory_on_gold_session', 0)}/{pref.get('questions', 0)} |"
            f" {a['memory_on_gold_turn']}/{a['questions']} |"
        )
    return "\n".join(lines) + "\n"


def main(splits: list[str]) -> dict:
    questions = {
        q["question_id"]: q
        for q in json.loads((REPO / "data/longmemeval_s_cleaned.json").read_text(encoding="utf-8"))
    }
    report = {"splits": {}}
    for split in splits:
        qids = json.loads((REPO / f"results/manifests/{split}.json").read_text(encoding="utf-8"))[
            "question_ids"
        ]
        con = sqlite3.connect(f"file:{REPO / 'stores' / split}.db?mode=ro", uri=True)
        try:
            report["splits"][split] = {
                "store": _store_counts(con),
                "questions": audit_split(questions, qids, con),
            }
        finally:
            con.close()
    return report


if __name__ == "__main__":
    report = main(sys.argv[1:] or ["train150", "dev100", "heldout100"])
    OUT.with_suffix(".json").write_text(json.dumps(report, indent=1) + "\n", encoding="utf-8")
    OUT.with_suffix(".md").write_text(render(report), encoding="utf-8")
    print(render(report))
