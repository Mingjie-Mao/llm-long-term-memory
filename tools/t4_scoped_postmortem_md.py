"""Render the verified request audit and separately authored first-loss notes."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))
from analysis_io import sha256_file  # noqa: E402


def main():
    stem = "t4-scoped-dev100-postmortem-v1"
    source = REPO / f"results/analysis/{stem}.json"
    notes = REPO / "research/T4_SCOPED_DEV100_POSTMORTEM.md"
    data = json.loads(source.read_text(encoding="utf-8"))
    for rel, digest in data["inputs"].items():
        if sha256_file(REPO / rel) != digest:
            raise ValueError(f"diagnostic input changed: {rel}")
    text = notes.read_text(encoding="utf-8")
    rows = {r["question_id"]: r for r in data["rows"]}
    annotated = re.findall(r"\| `([^`]+)` \|(\d+)/(\d+)\|", text)
    if {q for q, _, _ in annotated} != set(data["summary"]["negative_questions"]):
        raise ValueError("first-loss notes must cover every negative question")
    for q, c, t in annotated:
        if rows[q]["correct_out_of_three"] != {"control": int(c), "candidate": int(t)}:
            raise ValueError("first-loss notes' counts differ from verified audit")
    lines = [
        "<!-- Generated by tools/t4_scoped_postmortem_md.py; zero provider calls. -->",
        f"<!-- Request audit SHA256: {sha256_file(source)} -->",
        f"<!-- Authored first-loss notes SHA256: {sha256_file(notes)} -->",
        text.replace("../results/", "../").rstrip(),
        "",
        "## Complete100-question request/outcome inventory",
        "",
        "| Question | Type | Control/candidate correct out of3 | Majority regression |",
        "|---|---|---:|---|",
    ]
    for r in data["rows"]:
        counts = r["correct_out_of_three"]
        lines.append(
            f"| `{r['question_id']}` | {r['question_type']} | "
            f"{counts['control']}/{counts['candidate']} | {r['majority_regression']} |"
        )
    output = "\n".join(lines) + "\n"
    path = source.with_suffix(".md")
    if path.exists() and path.read_text(encoding="utf-8") != output:
        raise ValueError("immutable diagnostic report changed")
    if not path.exists():
        path.write_text(output, encoding="utf-8")
    print(
        json.dumps(
            {
                "provider_calls": 0,
                "questions": len(rows),
                "negative_cases_annotated": len(annotated),
            }
        )
    )


if __name__ == "__main__":
    main()
