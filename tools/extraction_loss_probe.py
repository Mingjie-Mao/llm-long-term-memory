"""Stage E of research/ROADMAP.md: are the values extraction lost recoverable?

    python tools/extraction_loss_probe.py

For each target in research/extraction-loss-targets-v1.json (23 knowledge-update
questions whose old or new value was never extracted), whether a memory from a gold
session carries the lost value, under three arms:

- `batch15`: the existing store, extracted 15 sessions per request (no calls);
- `batch8`: the gold sessions re-extracted with the nearest-dated sessions of the same
  history, 8 sessions per request, as `ingest.sessions_per_request: 8` would;
- `batch1`: each gold session extracted alone.

Same two-stage extractor, prompts and model as the stores. Re-extracted memories are
kept in the report only; no store is written. Calls go through a response cache.
Development evidence; the targets are the assistant's draft.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

TARGETS = REPO / "research/extraction-loss-targets-v1.json"
OUT = REPO / "results/analysis/extraction-loss-v1"
BATCH = 8


def _gold_sessions(instance) -> list:
    return [s for s in instance.sessions if any(t.has_answer for t in s.turns)]


def _batch8(instance) -> list:
    """The gold sessions plus the nearest-dated sessions of the same history, 8 in all."""
    from llm_long_term_memory.ingest.extract import _parse_date

    gold = _gold_sessions(instance)
    gold_dates = [_parse_date(s.date) for s in gold]
    others = [s for s in instance.sessions if s not in gold]

    def distance(session):
        when = _parse_date(session.date)
        return min(abs((when - g).total_seconds()) for g in gold_dates)

    return gold + sorted(others, key=lambda s: (distance(s), s.session_id))[: BATCH - len(gold)]


def main() -> dict:
    from llm_long_term_memory.config import ExperimentConfig, Settings
    from llm_long_term_memory.evaluation.datasets import longmemeval as lme
    from llm_long_term_memory.ingest.two_stage import TwoStageExtractor
    from llm_long_term_memory.llm import Limits, QuotaManager, UsageTracker
    from llm_long_term_memory.llm.cache import CachingClient
    from llm_long_term_memory.llm.client import GeminiClient
    from llm_long_term_memory.store import SQLiteMemoryStore, external_session_id

    settings = Settings()
    cfg = ExperimentConfig.from_yaml(REPO / "configs/fallback.yaml")
    quota = QuotaManager(
        state_dir=settings.store_dir / "quota",
        default=Limits(rpm=cfg.quota.rpm, tpm=cfg.quota.tpm, rpd=cfg.quota.rpd),
    )
    client = CachingClient(
        GeminiClient(settings.require_api_key(), quota=quota, usage=UsageTracker()),
        REPO / "stores/cache/extraction-loss-v1.db",
        sample="rep1",
    )
    targets = json.loads(TARGETS.read_text(encoding="utf-8"))["targets"]
    instances = {i.question_id: i for i in lme.load("s", settings.data_dir)}
    report = {"model": cfg.models.extractor, "batch": BATCH, "targets": []}
    for qid, target in targets.items():
        instance = instances[qid]
        gold_ids = {s.session_id for s in _gold_sessions(instance)}
        pattern = re.compile(target["pattern"], re.IGNORECASE)
        store = SQLiteMemoryStore(REPO / "stores" / f"{target['split']}.db", read_only=True)
        try:
            existing = [
                m.content
                for m in store.iter_all(qid)
                if external_session_id(m.source_session_id) in gold_ids
            ]
        finally:
            store.close()
        arms = {"batch15": existing}
        extractor = TwoStageExtractor(client, cfg.models.extractor, user_id=qid)
        outcome = extractor.extract(_batch8(instance))
        arms["batch8"] = [m.content for m in outcome.memories if m.source_session_id in gold_ids]
        arms["batch1"] = []
        for session in _gold_sessions(instance):
            outcome = extractor.extract([session])
            arms["batch1"] += [m.content for m in outcome.memories]
        report["targets"].append(
            {
                "question_id": qid,
                "side": target["side"],
                "value": target["value"],
                "recovered": {arm: any(pattern.search(c) for c in cs) for arm, cs in arms.items()},
                "memories_on_gold_sessions": {arm: len(cs) for arm, cs in arms.items()},
                "matching": {arm: [c for c in cs if pattern.search(c)] for arm, cs in arms.items()},
            }
        )
    return report


def render(report: dict) -> str:
    ts = report["targets"]
    arms = ("batch15", "batch8", "batch1")
    lines = [
        "# Can extraction recover the values it lost? (stage E)",
        "",
        f"> Generated by `tools/extraction_loss_probe.py`; extractor `{report['model']}`,",
        "> two-stage prompts as in the stores. Targets: research/extraction-loss-targets-v1.json",
        "> (assistant's draft). Development evidence.",
        "",
        "| arm | lost value recovered | memories on gold sessions |",
        "|---|---:|---:|",
    ]
    for arm in arms:
        found = sum(t["recovered"][arm] for t in ts)
        mems = sum(t["memories_on_gold_sessions"][arm] for t in ts)
        lines.append(f"| {arm} | {found}/{len(ts)} | {mems} |")
    lines += [
        "",
        "| question | side | value | " + " | ".join(arms) + " |",
        "|---|---|---|---|---|---|",
    ]
    for t in ts:
        marks = " | ".join("yes" if t["recovered"][a] else "" for a in arms)
        lines.append(f"| `{t['question_id']}` | {t['side']} | {t['value']} | {marks} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    report = main()
    OUT.with_suffix(".json").write_text(
        json.dumps(report, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    OUT.with_suffix(".md").write_text(render(report), encoding="utf-8")
    print(render(report))
